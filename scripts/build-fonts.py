#!/usr/bin/env python3
"""Builds the icon font bundled with the app (assets/fonts/Phosphor.ttf) and the icon
constants (src/ui/icon_codes.rs).

    python3 -m venv /tmp/ft && /tmp/ft/bin/pip install fonttools
    /tmp/ft/bin/python scripts/build-fonts.py --phosphor DIR [--inter DIR]

--phosphor   folder with Phosphor.ttf and codepoints.rs: the egui-phosphor crate's res/ and
             src/variants/ copied into one folder (or the Phosphor release)
--inter      folder with Inter-Regular/Medium/SemiBold.ttf (Inter 4.x release, extras/ttf);
             optional: the Inter files in assets/fonts are already cut down

The text fonts are cut down to the scripts the UI needs (Latin, punctuation, arrows, box
drawing, ...); other characters fall back to the system fonts. The icon font keeps only the
icons listed in ICONS. Inter is SIL OFL 1.1 and Phosphor MIT; their licenses sit next to them.
"""

import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "fonts")
ICONS_RS = os.path.join(ROOT, "src", "ui", "icon_codes.rs")

TEXT_RANGES = ",".join([
    "U+0000-024F",  # Basic Latin, Latin-1, Latin Extended-A/B
    "U+0259", "U+02B0-02FF", "U+0300-036F",
    "U+1E00-1EFF",  # Latin Extended Additional (Vietnamese, ...)
    "U+2000-206F",  # General punctuation
    "U+20A0-20CF",  # Currency
    "U+2100-214F",  # Letterlike
    "U+2190-21FF",  # Arrows
    "U+2200-22FF",  # Math operators
    "U+2300-23FF",  # Misc technical (⌘ ⌥ ⇧ ⏎ ...)
    "U+2460-24FF", "U+2500-25FF",  # Enclosed, box drawing, blocks, geometric shapes
    "U+2600-26FF", "U+2700-27BF",  # Misc symbols, dingbats (✓ ✗ ...)
    "U+FB00-FB06", "U+FFFD",
])

# Icons the app uses (Phosphor names); add one here, rerun, then use icons::NAME.
